"""Reproducible 50-case routing and grounding audit + ML holdout metrics.

Run from the project root: python backend/scripts/evaluate.py
"""
from __future__ import annotations
from datetime import datetime, timezone
import json
from pathlib import Path
import sys
from time import perf_counter

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'backend'))
from app.db import Base, engine, SessionLocal  # noqa: E402
from app.services.seed import seed_demo  # noqa: E402
from app.services.agent import answer_offline, detect_tools  # noqa: E402
from app.services.forecasting import forecast  # noqa: E402


def grounded_values_check(reply: dict, expected: list[str]) -> bool:
    """Smoke audit: verifiable tool values are explicitly present in the reply.
    This is NOT a full semantic hallucination detector, and is labeled accordingly.
    """
    text = reply['answer']
    actual = reply['tool_results']
    for name in expected:
        if name not in actual: return False
        if name == 'get_sales_summary':
            if str(actual[name]['orders']) not in text: return False
        elif name == 'get_top_products':
            if actual[name] and actual[name][0]['name'] not in text: return False
        elif name == 'get_demand_forecast':
            if str(actual[name]['tomorrow_units']) not in text: return False
        elif name == 'search_knowledge':
            if not all('source' in x and 'excerpt' in x for x in actual[name]['matches']): return False
        elif name == 'get_recent_orders':
            if actual[name] and actual[name][0]['id'] not in text: return False
        elif name == 'get_sales_timeseries':
            if not actual[name] or str(actual[name][-1]['orders']) not in text: return False
    return True


def run():
    cases = json.loads((ROOT/'eval'/'agent_cases.json').read_text(encoding='utf-8'))
    assert len(cases)==50, 'Evaluation suite must contain exactly 50 cases.'
    Base.metadata.create_all(engine)
    report_rows = []
    with SessionLocal() as db:
        seed_demo(db)
        for case in cases:
            start = perf_counter()
            result = answer_offline(db,case['question'])
            elapsed = round((perf_counter()-start)*1000,1)
            observed = result['tools_used']
            expected = case['expected_tools']
            exact = set(observed)==set(expected)
            recall = set(expected).issubset(set(observed))
            grounded = grounded_values_check(result,expected)
            report_rows.append({'id':case['id'],'question':case['question'],
                'expected_tools':expected,'observed_tools':observed,
                'exact_routing':exact,'required_tools_present':recall,
                'value_grounding_smoke_check':grounded,'time_ms':elapsed})
        ml=forecast(db)['evaluation']
    count=len(report_rows)
    stats={
        'evaluated_at_utc':datetime.now(timezone.utc).isoformat(),
        'dataset':'synthetic generated by backend/app/services/seed.py',
        'agent_mode':'local deterministic',
        'num_cases':count,
        'exact_tool_route_accuracy_pct':round(sum(x['exact_routing'] for x in report_rows)/count*100,1),
        'required_tool_recall_pct':round(sum(x['required_tools_present'] for x in report_rows)/count*100,1),
        'grounding_smoke_check_pct':round(sum(x['value_grounding_smoke_check'] for x in report_rows)/count*100,1),
        'average_latency_ms':round(sum(x['time_ms'] for x in report_rows)/count,1),
        'ml_metrics':ml,
        'limitations':[
            'Offline rule-based tool routing is evaluated, not OpenAI model semantic quality.',
            'Grounding smoke checks verify selected reference values, not full semantic factuality.',
            'Synthetic sales distributions may not represent any real restaurant.',
            'MAE is evaluated with chronological one-step predictions on the last 21 days.',
        ],
        'cases':report_rows,
    }
    out=ROOT/'reports'
    out.mkdir(exist_ok=True)
    (out/'evaluation.json').write_text(json.dumps(stats,ensure_ascii=False,indent=2),encoding='utf-8')
    markdown=f'''# FoodOps AI — Relatório de avaliação

Execução (UTC): {stats['evaluated_at_utc']}

## Escopo

Dados de vendas **sintéticos**. Foram avaliadas 50 perguntas em português no **roteador local determinístico**; o script não avalia a qualidade de uma resposta gerada pela OpenAI. A previsão usa um holdout cronológico separado do treino.

## Resultado do agente

| Indicador | Resultado |
|---|---:|
| Casos executados | {count} |
| Correspondência exata das ferramentas | {stats['exact_tool_route_accuracy_pct']}% |
| Recuperação de todas as ferramentas esperadas | {stats['required_tool_recall_pct']}% |
| Verificação pontual de valores na resposta | {stats['grounding_smoke_check_pct']}% |
| Latência média por pergunta (ambiente de execução) | {stats['average_latency_ms']} ms |

A verificação pontual de valores inspeciona presença de quantidades, identificadores ou fontes fornecidos pelas ferramentas. **Não prova ausência de alucinações**, não inspeciona todas as afirmações e não substitui avaliação humana.

## Demanda — comparativo temporal

| Métrica | Modelo RandomForest | Baseline: mesmo dia da semana anterior |
|---|---:|---:|
| MAE (unidades de item/dia) | {ml['model_mae']} | {ml['baseline_mae']} |
| WAPE | {ml['model_wape_pct']}% | {ml['baseline_wape_pct']}% |

Diferença relativa de MAE a favor do modelo: **{ml['improvement_mae_pct']}%** (valor negativo significa desempenho pior que a baseline). Foram avaliadas **{ml['observations']}** observações por produto/dia.

**Protocolo:** {ml['split']}. O modelo recebe calendário, últimas vendas e médias móveis. Nenhum dado de pedidos futuros entra como atributo; a avaliação mede previsão de um passo com histórico observado.

## Limitações e próximos passos

- Os dados são artificiais e não contêm feriados, clima, ruptura de estoque ou promoções.
- Não há backtesting de previsões recursivas de 7 dias; o teste de MAE é de um passo.
- O roteamento local usa regras linguísticas e pode classificar mensagens ambíguas incorretamente.
- A busca TF-IDF não captura todos os sinônimos; pgvector pode ser testado como alternativa opcional.
- Antes do uso comercial: autenticação, multiempresa, permissões, observabilidade e revisão de segurança.

## Reprodução

`python backend/scripts/evaluate.py` gera este arquivo e `reports/evaluation.json` com detalhes dos 50 casos.
'''
    (out/'evaluation.md').write_text(markdown,encoding='utf-8')
    snapshot = {k:v for k,v in stats.items() if k in ('evaluated_at_utc','num_cases','exact_tool_route_accuracy_pct','required_tool_recall_pct','grounding_smoke_check_pct','average_latency_ms')}
    (ROOT/'backend'/'app'/'evaluation_snapshot.json').write_text(json.dumps(snapshot,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps({k:v for k,v in stats.items() if k not in ('cases','limitations')},ensure_ascii=False,indent=2))


if __name__=='__main__': run()
